#!/usr/bin/env node
/**
 * Build docs/skills-catalog.md from every SKILL.md frontmatter.
 *
 * Output is a single browsable catalogue grouped by skill bucket
 * (actions / agents / core) with each skill's name, description, and
 * triggers — the user-facing surface in one place.
 *
 * Run: node scripts/build-skills-catalog.cjs
 *
 * No runtime dependencies. Re-runs are idempotent — output is deterministic
 * given the same input set.
 */

const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = path.resolve(__dirname, '..');
const SKILLS_DIR = path.join(PROJECT_ROOT, 'rihal', 'skills');
const OUTPUT = path.join(PROJECT_ROOT, 'docs', 'skills-catalog.md');

function parseFrontmatter(text) {
  if (!text.startsWith('---\n')) return {};
  const end = text.indexOf('\n---\n', 4);
  if (end === -1) return {};
  const block = text.slice(4, end);
  const fm = {};
  let currentKey = null;
  let currentList = null;
  for (const raw of block.split('\n')) {
    if (currentList && /^\s+-\s+/.test(raw)) {
      currentList.push(raw.replace(/^\s+-\s+/, '').replace(/^"/, '').replace(/"$/, '').trim());
      continue;
    }
    currentList = null;
    const m = raw.match(/^([a-zA-Z_-]+):\s*(.*)$/);
    if (!m) continue;
    const [, key, val] = m;
    currentKey = key;
    if (val === '' || val === '>' || val === '|') {
      // multiline value or list follows
      if (val === '') {
        currentList = [];
        fm[key] = currentList;
      } else {
        // multiline scalar — collect indented lines
        fm[key] = [];
      }
      continue;
    }
    let v = val.trim();
    if (v.startsWith('"') && v.endsWith('"')) v = v.slice(1, -1);
    if (v.startsWith("'") && v.endsWith("'")) v = v.slice(1, -1);
    fm[key] = v;
  }
  // Coerce list values to arrays already; coerce array-of-string-fragments to joined strings for descriptions
  for (const [k, v] of Object.entries(fm)) {
    if (Array.isArray(v) && k === 'description') fm[k] = v.join(' ').trim();
  }
  return fm;
}

function findSkills(dir) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const sub = path.join(dir, entry.name);
    const skillMd = path.join(sub, 'SKILL.md');
    if (fs.existsSync(skillMd)) {
      out.push(skillMd);
    } else {
      out.push(...findSkills(sub));
    }
  }
  return out;
}

function bucketOf(skillPath) {
  const rel = path.relative(SKILLS_DIR, skillPath);
  const parts = rel.split(path.sep);
  // rel = e.g. 'actions/4-implementation/foo/SKILL.md' or 'agents/dalil-scout/SKILL.md' or 'core/foo/SKILL.md'
  return parts[0];
}

function buildCatalog() {
  const files = findSkills(SKILLS_DIR);
  const byBucket = { actions: [], agents: [], core: [] };
  for (const f of files) {
    const text = fs.readFileSync(f, 'utf8');
    const fm = parseFrontmatter(text);
    const bucket = bucketOf(f);
    if (!byBucket[bucket]) byBucket[bucket] = [];
    byBucket[bucket].push({
      file: path.relative(PROJECT_ROOT, f),
      name: fm.name || path.basename(path.dirname(f)),
      description: typeof fm.description === 'string' ? fm.description.replace(/\s+/g, ' ').trim() : '',
      triggers: Array.isArray(fm.triggers) ? fm.triggers : [],
      lines: text.split('\n').length,
    });
  }
  for (const arr of Object.values(byBucket)) arr.sort((a, b) => a.name.localeCompare(b.name));
  return byBucket;
}

function render(catalog) {
  const lines = [];
  lines.push('<!-- DO NOT EDIT — generated by scripts/build-skills-catalog.cjs -->');
  lines.push('# Skills Catalogue');
  lines.push('');
  lines.push(`Auto-generated from every \`rihal/skills/**/SKILL.md\`. Re-run \`node scripts/build-skills-catalog.cjs\` after adding or renaming a skill.`);
  lines.push('');
  const total = Object.values(catalog).reduce((n, arr) => n + arr.length, 0);
  lines.push(`**${total} skills** across ${Object.keys(catalog).length} buckets.`);
  lines.push('');
  for (const bucket of ['actions', 'agents', 'core']) {
    const arr = catalog[bucket] || [];
    if (arr.length === 0) continue;
    const heading = bucket.charAt(0).toUpperCase() + bucket.slice(1);
    lines.push(`---`);
    lines.push('');
    lines.push(`## ${heading} (${arr.length})`);
    lines.push('');
    for (const s of arr) {
      lines.push(`### \`${s.name}\``);
      lines.push('');
      if (s.description) {
        // Collapse description to a single short paragraph
        const short = s.description.length > 600 ? s.description.slice(0, 600) + '…' : s.description;
        lines.push(short);
        lines.push('');
      }
      if (s.triggers.length) {
        lines.push('**Triggers:** ' + s.triggers.slice(0, 12).map((t) => `\`${t}\``).join(', '));
        lines.push('');
      }
      lines.push(`**Source:** [\`${s.file}\`](../${s.file}) — ${s.lines} lines`);
      lines.push('');
    }
  }
  return lines.join('\n');
}

const catalog = buildCatalog();
const out = render(catalog);
fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, out);
const total = Object.values(catalog).reduce((n, arr) => n + arr.length, 0);
console.log(`✓ wrote ${path.relative(PROJECT_ROOT, OUTPUT)} — ${total} skills`);
