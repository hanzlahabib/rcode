#!/usr/bin/env node
/**
 * Install-time generator: skill stubs that mirror slash commands.
 *
 * WHY: VS Code's Claude Code extension lists `.claude/skills/` in its
 * sidebar, but slash commands at `.claude/commands/rcode/` are only
 * reachable via the `/` autocomplete. Users expect to see lifecycle
 * commands like `rcode-do` in the sidebar — generating a thin skill
 * stub per command makes them browsable without duplicating real skills.
 *
 * This script creates ONE skill stub per slash command at install time,
 * unless a real skill with the same name already exists at the source.
 * The stubs live at the install destination only (`.claude/skills/`) —
 * they are NEVER committed to the rcode source tree. That keeps the
 * source codebase free of duplication while letting the sidebar feel
 * full.
 *
 * Each generated stub is marked with `generated: true` and
 * `generated-by: rcode-install` in frontmatter so it can be detected
 * and refreshed on subsequent installs without confusing real skills.
 *
 * Run: node cli/generate-command-skills.cjs <package-root> <target-skills-dir>
 *      (called from cli/install.js)
 */

const fs = require('fs');
const path = require('path');

/**
 * Curated list of commands that get skill stubs.
 *
 * Issue #710: sidebar-stub bloat. The picker has a token budget for skill
 * descriptions; every stub here counts. Pre-#710 this list had 43 entries —
 * the user hit "491 descriptions dropped" because rcode + plugins blew the
 * budget. Trimmed to the minimum set users actually pick from the sidebar:
 * navigation + the verb-style commands they invoke daily.
 *
 * Everything else stays reachable via `/` autocomplete (claude-code reads
 * .claude/commands/ for slash dispatch — sidebar stubs are UX sugar, not
 * functional). Power users running niche commands like /rcode-prfaq or
 * /rcode-ui-phase still get them — they just don't show up in the sidebar.
 */
// Minimal set — only the primary entry-point command that users expect to
// find browsable in the sidebar. CC 2.x shows all .claude/commands/ in slash
// autocomplete, so stubs are UX sugar only. Issue #710 required trimming
// from 43 → 1 to avoid "491 descriptions dropped" budget exhaustion.
const SIDEBAR_COMMANDS = new Set([
  'do', // primary router — users pick workflows from the sidebar via /rcode-do
]);

function parseFrontmatter(text) {
  if (!text.startsWith('---\n')) return {};
  const end = text.indexOf('\n---\n', 4);
  if (end === -1) return {};
  const block = text.slice(4, end);
  const fm = {};
  for (const raw of block.split('\n')) {
    const m = raw.match(/^([a-zA-Z_-]+):\s*(.+)$/);
    if (m) fm[m[1].trim()] = m[2].trim().replace(/^["']|["']$/g, '');
  }
  return fm;
}

function discoverRealSkills(packageRoot) {
  const out = new Set();
  const buckets = ['core', 'agents'];
  for (const bucket of buckets) {
    const dir = path.join(packageRoot, 'rcode', 'skills', bucket);
    if (!fs.existsSync(dir)) continue;
    for (const entry of fs.readdirSync(dir)) {
      if (entry.startsWith('rcode-')) out.add(entry);
    }
  }
  // actions are nested by phase
  const actionsDir = path.join(packageRoot, 'rcode', 'skills', 'actions');
  if (fs.existsSync(actionsDir)) {
    for (const phase of fs.readdirSync(actionsDir)) {
      const phaseDir = path.join(actionsDir, phase);
      if (!fs.statSync(phaseDir).isDirectory()) continue;
      for (const entry of fs.readdirSync(phaseDir)) {
        if (entry.startsWith('rcode-')) out.add(entry);
      }
    }
  }
  return out;
}

function generateStub(cmdName, commandFm, version) {
  const desc = commandFm.description || `Slash command shortcut for /rcode-${cmdName}.`;
  const triggers = [
    `rcode ${cmdName}`,
    `rcode-${cmdName}`,
    `/rcode-${cmdName}`,
  ];

  return `---
name: rcode-${cmdName}
description: >
  ${desc.replace(/\n/g, ' ')}
  Sidebar entry — invokes the same workflow as /rcode-${cmdName}.
triggers:
${triggers.map((t) => `  - "${t}"`).join('\n')}
user-invocable: true
generated: true
generated-by: rcode-install-v${version}
source: rcode/commands/${cmdName}.md
---

<!--
AUTO-GENERATED at install time by cli/generate-command-skills.cjs.
Do NOT edit this file directly — your changes will be overwritten on the next
install or update. To customise, create a sibling \`.local.md\` file (which
is preserved across installs) or modify the source command at
rcode/commands/${cmdName}.md.

This stub exists so the slash command /rcode-${cmdName} appears in VS Code's
Claude Code sidebar (which lists skills only, not slash commands). The
behaviour is identical to /rcode-${cmdName} — both invoke the workflow at
.rcode/workflows/${cmdName}.md.
-->

## Overview

Sidebar entry for the \`/rcode-${cmdName}\` slash command. Phrase-activated alternative invocation route.

## Workflow

Read and execute \`@.rcode/workflows/${cmdName}.md\` end-to-end. The behaviour is the same as invoking \`/rcode-${cmdName}\` directly.

## Output Format

Identical to \`/rcode-${cmdName}\`. See the workflow file for the canonical output spec.

## Examples

**Happy path** — say "rcode ${cmdName}" or "/rcode-${cmdName}" → workflow runs identically either way.

**Negative — looking for the canonical command file** — see \`rcode/commands/${cmdName}.md\` (the source of truth) and \`rcode/workflows/${cmdName}.md\` (the orchestration logic).

## Memory Bank Hooks

- **Reads:** whatever \`.rcode/workflows/${cmdName}.md\` reads
- **Writes:** whatever the workflow writes
- This stub itself is read-only — it just dispatches to the workflow.
`;
}

function main(packageRoot, targetSkillsDir, version, options = {}) {
  if (!fs.existsSync(targetSkillsDir)) {
    fs.mkdirSync(targetSkillsDir, { recursive: true });
  }

  const realSkills = discoverRealSkills(packageRoot);
  const commandsDir = path.join(packageRoot, 'rcode', 'commands');
  if (!fs.existsSync(commandsDir)) {
    console.warn(`[generate-command-skills] commands dir not found: ${commandsDir}`);
    return { generated: 0, skipped: 0, skippedGlobal: 0 };
  }

  // Issue #679: skip stubs whose name already exists in ~/.claude/skills/.
  // Otherwise the slash picker shows the same /rcode-* twice.
  const os = require('os');
  const globalSkillsDir = path.join(os.homedir(), '.claude', 'skills');
  const globalSkills = (options.skipGlobalDuplicates && fs.existsSync(globalSkillsDir))
    ? new Set(fs.readdirSync(globalSkillsDir).filter(n => n.startsWith('rcode-')))
    : new Set();

  let generated = 0;
  let skipped = 0;
  let skippedGlobal = 0;

  for (const file of fs.readdirSync(commandsDir)) {
    if (!file.endsWith('.md')) continue;
    if (file.startsWith('_')) continue; // internal aliases / metadata
    const cmdName = file.replace(/\.md$/, '');
    if (!SIDEBAR_COMMANDS.has(cmdName)) { skipped++; continue; }

    const skillName = `rcode-${cmdName}`;
    if (realSkills.has(skillName)) {
      // A real skill with this name exists in the source tree — don't shadow it
      skipped++;
      continue;
    }

    if (globalSkills.has(skillName)) {
      // Global skill of same name exists — installing a sidebar stub here would
      // duplicate the entry in Claude Code's slash picker. Also clean up any
      // previously-generated stub with the same name.
      const existingStub = path.join(targetSkillsDir, skillName);
      if (fs.existsSync(existingStub)) {
        try {
          const existingFile = path.join(existingStub, 'SKILL.md');
          if (fs.existsSync(existingFile)) {
            const text = fs.readFileSync(existingFile, 'utf8');
            // Only delete previously-generated stubs (marker present) — never
            // user customizations.
            if (/^generated:\s*true/m.test(text)) {
              fs.rmSync(existingStub, { recursive: true, force: true });
            }
          }
        } catch { /* non-fatal */ }
      }
      skippedGlobal++;
      continue;
    }

    const cmdPath = path.join(commandsDir, file);
    const cmdText = fs.readFileSync(cmdPath, 'utf8');
    const cmdFm = parseFrontmatter(cmdText);

    const stubDir = path.join(targetSkillsDir, skillName);
    const stubFile = path.join(stubDir, 'SKILL.md');

    // Idempotency: only overwrite if the file is missing OR is a previously
    // generated stub (has the marker). Never clobber a user's hand-edited file.
    if (fs.existsSync(stubFile)) {
      const existing = fs.readFileSync(stubFile, 'utf8');
      if (!/^generated:\s*true/m.test(existing)) {
        skipped++;
        continue;
      }
    }

    fs.mkdirSync(stubDir, { recursive: true });
    fs.writeFileSync(stubFile, generateStub(cmdName, cmdFm, version), 'utf8');
    generated++;
  }

  // Cleanup stale stubs: generated stubs whose command was removed from
  // SIDEBAR_COMMANDS still block the corresponding ~/.claude/commands/ file
  // in Claude Code 2.x (skill with user-invocable:false overrides the command).
  // Delete any generated stub for a command no longer in the curated set.
  let cleaned = 0;
  try {
    for (const entry of fs.readdirSync(targetSkillsDir)) {
      if (!entry.startsWith('rcode-')) continue;
      const cmdName = entry.replace(/^rcode-/, '');
      if (SIDEBAR_COMMANDS.has(cmdName)) continue; // still wanted — leave it
      if (realSkills.has(entry)) continue;          // real skill — never touch
      const skillFile = path.join(targetSkillsDir, entry, 'SKILL.md');
      if (!fs.existsSync(skillFile)) continue;
      const text = fs.readFileSync(skillFile, 'utf8');
      // Only remove stubs that were auto-generated from a command file.
      if (!/^generated:\s*true/m.test(text)) continue;
      if (!/^source:\s*rcode\/commands\//m.test(text)) continue;
      fs.rmSync(path.join(targetSkillsDir, entry), { recursive: true, force: true });
      cleaned++;
    }
  } catch { /* non-fatal */ }

  return { generated, skipped, cleaned };
}

if (require.main === module) {
  const [packageRoot, targetSkillsDir, version = '0.0.0'] = process.argv.slice(2);
  if (!packageRoot || !targetSkillsDir) {
    console.error('Usage: generate-command-skills.cjs <package-root> <target-skills-dir> [version]');
    process.exit(2);
  }
  const { generated, skipped, cleaned } = main(packageRoot, targetSkillsDir, version);
  console.log(`✓ ${generated} sidebar skill stub${generated === 1 ? '' : 's'} generated, ${skipped} skipped, ${cleaned} stale stubs cleaned`);
}

module.exports = { main, SIDEBAR_COMMANDS };
